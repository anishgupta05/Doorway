// "The room builds itself from code": Argon's scene.json scrolls by while each
// object drops into the room as its block streams past.
import { useEffect, useMemo, useRef } from "react";
import { motion } from "framer-motion";
import type { Scene } from "@doorway/schema";
import { useApp } from "../store";
import { sfx } from "../sfx";

const FIRST_DELAY = 1100;
const PER_OBJECT = 520;

export function BuildPanel({ scene }: { scene: Scene }) {
  const count = useApp((s) => s.buildCount) ?? 0;
  const scroller = useRef<HTMLDivElement>(null);

  // Line ranges of each object's block in the pretty-printed JSON.
  const { lines, blocks } = useMemo(() => {
    const head = JSON.stringify({ version: scene.version, name: scene.name, room: scene.room }, null, 2).split("\n").slice(0, -1);
    const lines: string[] = [...head.map((l, i) => (i === head.length - 1 ? l + "," : l)), '  "objects": ['];
    const blocks: [number, number][] = [];
    scene.objects.forEach((o, i) => {
      const body = JSON.stringify(o, null, 2)
        .split("\n")
        .map((l) => "    " + l);
      if (i < scene.objects.length - 1) body[body.length - 1] += ",";
      blocks.push([lines.length, lines.length + body.length]);
      lines.push(...body);
    });
    lines.push("  ],", `  "interactions": ${JSON.stringify(scene.interactions)}`, "}");
    return { lines, blocks };
  }, [scene]);

  useEffect(() => {
    const timers: number[] = [];
    scene.objects.forEach((_, i) => {
      timers.push(
        window.setTimeout(() => {
          useApp.getState().setBuildCount(i + 1);
          sfx.tick();
        }, FIRST_DELAY + i * PER_OBJECT),
      );
    });
    timers.push(window.setTimeout(() => useApp.getState().setBuildCount(null), FIRST_DELAY + scene.objects.length * PER_OBJECT + 2200));
    sfx.whoosh();
    return () => timers.forEach(clearTimeout);
    // Restart when a new build starts.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [useApp.getState().buildStart]);

  const active = blocks[Math.max(0, count - 1)];
  useEffect(() => {
    if (!active || !scroller.current) return;
    const lineH = 17;
    scroller.current.scrollTo({ top: Math.max(0, active[0] * lineH - 120), behavior: "smooth" });
  }, [active]);

  return (
    <motion.div
      initial={{ x: -40, opacity: 0 }}
      animate={{ x: 0, opacity: 1 }}
      exit={{ x: -40, opacity: 0 }}
      transition={{ type: "spring", stiffness: 240, damping: 28 }}
      className="absolute top-20 bottom-24 left-5 z-10 flex w-[400px] flex-col overflow-hidden rounded-2xl border border-line bg-ink/85 shadow-2xl backdrop-blur-md"
    >
      <div className="flex items-center justify-between border-b border-line px-4 py-2.5">
        <div className="font-mono text-[11px] text-muted">
          <span className="text-fg">scene.json</span> · generated by Argon in one pass
        </div>
        <div className="font-mono text-[11px] text-accent tabular">
          {count}/{scene.objects.length} objects
        </div>
      </div>
      <div ref={scroller} className="flex-1 overflow-hidden px-4 py-3 font-mono text-[11.5px] leading-[17px]">
        {lines.map((l, i) => {
          const inActive = active && count > 0 && i >= active[0] && i < active[1];
          const built = blocks.some(([a, b], j) => j < count && i >= a && i < b);
          return (
            <div key={i} className={`whitespace-pre transition-colors duration-300 ${inActive ? "bg-accent/10 text-fg" : built ? "text-muted" : "text-dim"}`}>
              <Highlight line={l} />
            </div>
          );
        })}
      </div>
    </motion.div>
  );
}

/** Minimal JSON coloring: keys, strings, numbers. */
function Highlight({ line }: { line: string }) {
  const parts = line.split(/("(?:[^"\\]|\\.)*"(?=\s*:)|"(?:[^"\\]|\\.)*"|-?\d+\.?\d*)/g);
  return (
    <>
      {parts.map((p, i) =>
        i % 2 === 0 ? (
          p
        ) : /:\s*$/.test(parts[i + 1] ?? "") || (parts[i + 1] ?? "").trimStart().startsWith(":") ? (
          <span key={i} className="text-[#9db4d0]">{p}</span>
        ) : p.startsWith('"') ? (
          <span key={i} className="text-[#d8c38e]">{p}</span>
        ) : (
          <span key={i} className="text-accent/90">{p}</span>
        ),
      )}
    </>
  );
}
